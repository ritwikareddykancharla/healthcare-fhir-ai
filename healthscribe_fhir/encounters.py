def get_encounter(encounter_id: str) -> Dict[str, Any]:
    if encounter_id not in SYNTHETIC_ENCOUNTERS:
        raise KeyError(f"Unknown synthetic encounter_id: {encounter_id}")
    return SYNTHETIC_ENCOUNTERS[encounter_id]


def list_encounters_summary() -> List[Dict[str, Any]]:
    summaries: List[Dict[str, Any]] = []
    for enc_id, enc in SYNTHETIC_ENCOUNTERS.items():
        summaries.append(
            {
                "encounter_id": enc_id,
                "synthetic_label": enc["synthetic_label"],
                "specialty": enc["specialty"],
                "title": enc["title"],
                "visit_date": enc["visit_date"],
                "requested_cpt": enc["requested_cpt"],
                "utterance_count": len(enc["utterances"]),
                "utterances": enc["utterances"],
                "patient_preview": {
                    "gender": enc["patient"]["gender"],
                    "mrn": enc["patient"]["mrn"],
                },
            }
        )
    return summaries
